#!/usr/bin/env python3
"""Extract method IDs from the official builder's ACAB, never invent a hash
algorithm. Mirrors examples/bounty-escrow/scripts/sync_ids.py exactly
(ACAB v1 method records prefix names with u64 ID/u16 flags/u32 input ID/u16
name length); pinned to that layout and fails on incompatible ABI.
"""
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parents[1]
METHODS = {
    "STAKE": "staking.rewards.stake",
    "UNSTAKE": "staking.rewards.unstake",
    "CLAIM": "staking.rewards.claim",
    "FUND_REWARDS": "staking.rewards.fund_rewards",
    "DEPLOY": "staking.rewards.deploy",
}
# No CALLBACK entry: callbacks use a dynamic per-request `pending_id` as
# their own `method_id` (see docs/SPEC.md's "Callback model"), not a fixed
# hash-derived selector, and
# the ABI declares no "staking.rewards.callback" method.

# The test-only toggleable receiver fixture's own methods.
RECEIVER_METHODS = {
    "BIND": "staking.receiver.bind",
    "TOGGLE": "staking.receiver.toggle",
    "SEND": "staking.receiver.send",
}


def identifier(contract, name, prefix):
    data = (ROOT / "contracts" / contract / "target/avm/contract.acab").read_bytes()
    encoded = name.encode()
    positions = [
        i
        for i in range(len(data))
        if data[i : i + len(encoded)] == encoded
        and int.from_bytes(data[i - 2 : i], "little") == len(encoded)
    ]
    if data[:4] != b"ACAB":
        raise ValueError(f"Unexpected canonical ABI: {name}")
    if len(positions) != 1:
        raise ValueError(f"Ambiguous name record: {name}")
    pos = positions[0]
    value = int.from_bytes(data[pos - prefix : pos - prefix + 8], "little")
    if value == 0:
        raise ValueError(f"Zero identifier: {name}")
    return value


def render_full():
    lines = ["// Generated by scripts/sync_ids.py from the official builder's canonical ACAB."]
    for key, name in METHODS.items():
        if key == "DEPLOY":
            continue
        lines.append(f"pub const {key}: u64 = 0x{identifier('staking-rewards', name, 16):016x};")
    lines.append(
        "// Read by off-chain deploy tooling (constructing the deploy envelope's own"
    )
    lines.append(
        "// method_id), not by this crate's own dispatch -- init() is invoked"
    )
    lines.append(
        "// directly by the runtime, never routed through process_message's match."
    )
    lines.append("#[allow(dead_code)]")
    lines.append(f"pub const DEPLOY: u64 = 0x{identifier('staking-rewards', 'staking.rewards.deploy', 16):016x};")
    lines.append("")
    errors = [
        ("INVALID_ARGS", 3000),
        ("UNAUTHORIZED", 3001),
        ("INVALID_STATE", 3002),
        ("SEQ_MISMATCH", 3003),
        ("BAD_EXPIRY", 3004),
        ("WRONG_CURRENCY", 3005),
        ("UNSOLICITED_CURRENCY", 3006),
        ("PENDING_IN_FLIGHT", 3007),
        ("NO_PENDING_PAYOUT", 3008),
        ("BELOW_MIN_STAKE", 3009),
        ("EXCEEDS_MAX_AMOUNT", 3010),
        ("FUND_REJECTED_NO_STAKERS", 3011),
        ("FUND_EXCEEDS_MAX_ACC", 3012),
        ("FUND_DELTA_ZERO", 3013),
        ("NOTHING_TO_CLAIM", 3014),
        ("TOO_MANY_ROWS", 3015),
        ("INVALID_MIN_STAKE", 3016),
        ("INVALID_CALLBACK", 3017),
        ("ROW_NOT_FOUND", 3018),
        ("INVALID_FUEL_RESERVE", 3019),
        ("CURRENCY_CANNOT_BE_SHELL", 3020),
    ]
    lines.append("// Error status codes are plain literals mirrored from avm-contract.toml,")
    lines.append("// not hash-derived.")
    for key, code in errors:
        lines.append(f"pub const {key}: u32 = {code};")
    return "\n".join(lines) + "\n"


def render_receiver():
    lines = ["// Generated by scripts/sync_ids.py from the official builder's canonical ACAB."]
    for key, name in RECEIVER_METHODS.items():
        lines.append(f"pub const {key}: u64 = 0x{identifier('test-receiver', name, 16):016x};")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    targets = [
        (ROOT / "contracts/staking-rewards/src/ids.rs", render_full()),
        (ROOT / "contracts/test-receiver/src/ids.rs", render_receiver()),
    ]
    if args.check:
        for path, expected in targets:
            if path.read_text() != expected:
                raise SystemExit(f"Canonical IDs differ in {path}; run scripts/sync_ids.py and rebuild.")
        print("Canonical method/error IDs: PASS")
    else:
        for path, expected in targets:
            path.write_text(expected)
        print("Canonical IDs updated; rebuild the contracts.")
