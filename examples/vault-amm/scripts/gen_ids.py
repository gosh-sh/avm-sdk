#!/usr/bin/env python3
"""Generate (or check) contracts/amm/src/ids.rs from the two ABI manifests.

Method and event identifiers are `blake3(name)[0..8]` read as a little-endian
u64. That rule was recovered by reproducing, byte for byte, every identifier in
the checked-in `bounty-escrow` and `fungible-token` examples (which the official
builder produced); `--selftest` repeats that reproduction against the sibling
example sources so a builder change cannot go unnoticed.

The official builder remains the authority. After building with
`avm-contract-build`, run `scripts/check_acab.py` (or compare the ACAB records as
`bounty-escrow/scripts/sync_ids.py` does) to confirm the generated constants.

Requires the `blake3` Python package (`pip install blake3`).
"""
import argparse
import pathlib
import re
import sys
import tomllib

import blake3

ROOT = pathlib.Path(__file__).resolve().parents[1]
EXAMPLES = ROOT.parent
IDS_RS = ROOT / "contracts/amm/src/ids.rs"


def ident(name: str) -> int:
    return int.from_bytes(blake3.blake3(name.encode()).digest()[:8], "little")


def load(contract: str) -> dict:
    with open(ROOT / "contracts" / contract / "avm-contract.toml", "rb") as handle:
        return tomllib.load(handle)["abi"]


def const_name(name: str) -> str:
    return name.split(".", 2)[-1].upper() if name.startswith("vault.") else name.replace(".", "_").upper()


def render() -> str:
    lines = ["// Generated by scripts/gen_ids.py from the ABI manifests. Do not edit.",
             "// id = u64::from_le_bytes(blake3(name)[0..8]); see scripts/gen_ids.py."]
    seen = {}
    for contract in ("amm", "receiver"):
        for method in load(contract)["methods"]:
            name = method["name"]
            key = ("RECEIVER_" if contract == "receiver" else "") + const_name(name)
            value = ident(name)
            if value == 0 or value in seen:
                raise SystemExit(f"identifier collision or zero for {name}")
            seen[value] = name
            lines.append(f"pub const {key}: u64 = 0x{value:016x};")
    events = []
    for event in load("amm")["events"]:
        name = event["name"]
        value = ident(name)
        if value == 0 or value in seen:
            raise SystemExit(f"identifier collision or zero for {name}")
        seen[value] = name
        key = "EVENT_" + name.split(".", 1)[1].upper()
        lines.append(f"pub const {key}: u64 = 0x{value:016x};")
        events.append((name, key))
    lines.append("")
    lines.append("/// Event name to class lookup used by the emitter.")
    lines.append("pub const EVENTS: &[(&str, u64)] = &[")
    for name, key in events:
        lines.append(f'    ("{name}", {key}),')
    lines.append("];")
    return "\n".join(lines) + "\n"


def selftest() -> None:
    """Reproduce every identifier of the official sibling examples."""
    checked = 0
    escrow_ids = (EXAMPLES / "bounty-escrow/contracts/escrow/src/ids.rs").read_text()
    escrow_names = {
        "FUND": "bounty.escrow.fund", "SUBMIT": "bounty.escrow.submit",
        "APPROVE": "bounty.escrow.approve", "PAY": "bounty.escrow.pay",
        "REFUND": "bounty.escrow.refund", "CALLBACK": "bounty.escrow.callback",
        "STATUS": "bounty.escrow.status", "TOPUP": "bounty.escrow.topup",
        "RECEIVE": "bounty.receiver.receive", "BIND": "bounty.receiver.bind",
        "REJECT": "bounty.receiver.reject",
        "EVENT_CREATED": "escrow.created", "EVENT_STATUS": "escrow.status",
        "EVENT_FEES_ADDED": "escrow.fees_added", "EVENT_FUNDED": "escrow.funded",
        "EVENT_SUBMITTED": "escrow.submitted", "EVENT_APPROVED": "escrow.approved",
        "EVENT_TRANSFER_PENDING": "escrow.transfer_pending",
        "EVENT_TRANSFER_SETTLED": "escrow.transfer_settled",
        "EVENT_TRANSFER_FAILED": "escrow.transfer_failed",
    }
    for const, name in escrow_names.items():
        match = re.search(rf"pub const {const}: u64 = 0x([0-9a-f]{{16}});", escrow_ids)
        assert match, const
        assert int(match.group(1), 16) == ident(name), f"{name} does not match the official builder"
        checked += 1
    token = (EXAMPLES / "fungible-token/src/lib.rs").read_text()
    for const, name in (("TRANSFER_METHOD_ID", "token.transfer"),
                        ("TRANSFERRED_EVENT_CLASS", "token.transferred")):
        match = re.search(rf"const {const}: u64 = 0x([0-9a-f_]+);", token)
        assert match, const
        assert int(match.group(1).replace("_", ""), 16) == ident(name), name
        checked += 1
    print(f"identifier rule reproduces {checked}/{checked} official identifiers: PASS")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if ids.rs is stale")
    parser.add_argument("--selftest", action="store_true", help="verify the rule on sibling examples")
    args = parser.parse_args()
    if args.selftest:
        selftest()
    expected = render()
    if args.check:
        if IDS_RS.read_text() != expected:
            sys.exit("ids.rs is stale; run scripts/gen_ids.py")
        print("ids.rs matches the manifests: PASS")
    elif not args.selftest:
        IDS_RS.write_text(expected)
        print(f"wrote {IDS_RS.relative_to(ROOT)}")
